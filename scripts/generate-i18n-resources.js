/**
 * ライブラリ内蔵 i18next インスタンス用のリソースを生成する。
 *
 * src/components 内の t("key") / t(`prefix.${...}`) を走査し、実際に使用される
 * キーのみを public/locales/<lang>/*.json から抽出して、**名前空間ごとに 1 ファイル**
 * （src/i18n/generated/<ns>.ts）へ出力する。これにより、利用側が i18next を
 * セットアップしなくてもコンポーネントの aria-label 等が正しく表示される。
 *
 * **1 つの塊にしない理由（T318）。** 以前は全部を resources.ts の 1 つのオブジェクトに
 * まとめていたので、`import { Button }` だけの利用者も、Audio や QueryBuilder、PhoneInput の
 * 国名の文言まで受け取っていた（`{ Button }` 単体 15.15 kB のうち約 10 kB）。部品は自分が
 * 使う名前空間のファイルだけを import し、残りは tree-shaking で落ちる。
 *
 * Usage: node scripts/generate-i18n-resources.js
 */

import fs from "fs";
import path from "path";
import { globSync } from "glob";

const localesDir = "./public/locales";
const srcDir = "./src/components";
const outDir = "./src/i18n/generated";
const keysFile = "./src/i18n/generated/keys.ts";
const localesFile = "./src/i18n/generated/locales.ts";
const langs = ["en", "ja", "pt"];

// Component-facing namespaces (everything that is not documentation copy).
const isComponentNs = (ns) => !ns.startsWith("docs_") && ns !== "audit";
const PLURAL_SUFFIXES = ["zero", "one", "two", "few", "many", "other"];

// ---- locale 読み込み: locales[lang][ns] = flat { "a.b.c": value } ----
function flatten(obj, prefix = "") {
  const acc = {};
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v !== null && typeof v === "object" && !Array.isArray(v)) {
      Object.assign(acc, flatten(v, key));
    } else {
      acc[key] = v;
    }
  }
  return acc;
}

const locales = {};
for (const lang of langs) {
  locales[lang] = {};
  const dir = path.join(localesDir, lang);
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    const ns = file.replace(".json", "");
    locales[lang][ns] = flatten(
      JSON.parse(fs.readFileSync(path.join(dir, file), "utf8")),
    );
  }
}

// ---- コンポーネントから使用キーを抽出 ----
const files = globSync(`${srcDir}/**/*.{ts,tsx}`, { posix: true }).filter(
  (f) => !f.includes(".test.") && !f.includes(".stories."),
);

const usedKeys = new Set();
const usedPrefixes = new Set();
for (const file of files) {
  const source = fs.readFileSync(file, "utf8");
  // リテラルキー: t("key") / t('key')（"ns:key" 形式は ns を除去）
  for (const m of source.matchAll(/\bt\(\s*["']([^"']+)["']/g)) {
    const raw = m[1];
    usedKeys.add(raw.includes(":") ? raw.split(":")[1] : raw);
  }
  // 動的キー: t(`prefix.${...}`) → prefix 配下を一括バンドル
  for (const m of source.matchAll(/\bt\(\s*`([^`$]*)\$\{/g)) {
    if (m[1]) usedPrefixes.add(m[1]);
  }
}

// ---- 言語ごとに使用キーのみ抽出（en に存在する ns 構成を正とする）----
function setDeep(target, dottedKey, value) {
  const parts = dottedKey.split(".");
  let node = target;
  for (const part of parts.slice(0, -1)) {
    node = node[part] ??= {};
  }
  node[parts[parts.length - 1]] = value;
}

const resources = {};
const usedNamespaces = new Set();
const missing = [];

for (const lang of langs) {
  resources[lang] = {};
  for (const [ns, flat] of Object.entries(locales[lang])) {
    const picked = {};
    for (const [key, value] of Object.entries(flat)) {
      const base = key.replace(
        new RegExp(`_(${PLURAL_SUFFIXES.join("|")})$`),
        "",
      );
      const hit =
        usedKeys.has(key) ||
        usedKeys.has(base) ||
        [...usedPrefixes].some((p) => key.startsWith(p));
      if (hit) setDeep(picked, key, value);
    }
    if (Object.keys(picked).length > 0) {
      resources[lang][ns] = picked;
      usedNamespaces.add(ns);
    }
  }
}

// 未解決キーの警告（存在チェック自体は check-i18n-components.js が担う）
const allEnKeys = new Set(
  Object.values(locales.en).flatMap((flat) => Object.keys(flat)),
);
for (const key of usedKeys) {
  if (!allEnKeys.has(key)) missing.push(key);
}
if (missing.length > 0) {
  console.warn(
    `[i18n-resources] WARNING: ${missing.length} key(s) not found in en locales:\n  ${missing.join("\n  ")}`,
  );
}

// ---- 出力 ----
const HEADER =
  "// This file is auto-generated by scripts/generate-i18n-resources.js. Do not edit manually.\n";

/** 変わったときだけ書く（生成物のタイムスタンプで HMR を起こさないため）。 */
function writeIfChanged(file, content, note) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (current === content) return false;
  fs.writeFileSync(file, content);
  console.log(`[i18n-resources] Generated ${file}${note ? ` (${note})` : ""}`);
  return true;
}

/** "data-display" → "dataDisplay" */
const camel = (ns) => ns.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
/** 部品が import する定数の名前。`form` や `common` は部品の中の変数名と衝突しやすいので Ns を付ける。 */
const nsConstName = (ns) => `${camel(ns)}Ns`;
const nsTypeName = (ns) => `${camel(ns).replace(/^./, (c) => c.toUpperCase())}Key`;

const stripPlural = (key) => key.replace(new RegExp(`_(${PLURAL_SUFFIXES.join("|")})$`), "");

const namespaces = [...usedNamespaces].sort();
let changed = 0;
for (const ns of namespaces) {
  // 型: その名前空間の en キー全体（複数形サフィックスは実行時に解決するので base 形だけ）。
  // useWimTranslation に渡した名前空間のキーだけが t() に通る＝名前空間の指定違いは tsc が落とす。
  const keyNames = [...new Set(Object.keys(locales.en[ns]).map(stripPlural))].sort();
  const byLang = Object.fromEntries(langs.map((lang) => [lang, resources[lang][ns] ?? {}]));
  const content = `${HEADER}// src/components が実際に使用する翻訳キーのうち、名前空間 "${ns}" の分（内蔵 i18n ストア用）。
import type { WimNamespace } from "../instance";

export type ${nsTypeName(ns)} =
${keyNames.map((k) => `  | ${JSON.stringify(k)}`).join("\n")};

export const ${nsConstName(ns)}: WimNamespace<${JSON.stringify(ns)}, ${nsTypeName(ns)}> = {
  name: ${JSON.stringify(ns)},
  resources: ${JSON.stringify(byLang, null, 2).replace(/\n/g, "\n  ")},
};
`;
  if (writeIfChanged(path.join(outDir, `${ns}.ts`), content, `${keyNames.length} key literals`)) changed++;
}

// 以前の 1 つの塊と、もう使っていない名前空間のファイルは消す（残っていると、誰かが import して塊が戻る）。
const keep = new Set([...namespaces.map((ns) => `${ns}.ts`), "keys.ts", "locales.ts"]);
for (const file of fs.readdirSync(outDir)) {
  if (!keep.has(file)) {
    fs.rmSync(path.join(outDir, file));
    console.log(`[i18n-resources] Removed ${path.join(outDir, file)}`);
    changed++;
  }
}

// 対応する言語の一覧。ロケールの状態（instance.ts）が、翻訳の実体を import せずに済むように分けてある。
if (
  writeIfChanged(
    localesFile,
    `${HEADER}export const wimLocales: readonly string[] = ${JSON.stringify(langs)};\n`,
  )
)
  changed++;

// ---- 型: 有効な翻訳キーの union（全部の名前空間。bare と "ns:key" の両方）----
const keysContent = `${HEADER}// 有効な component 翻訳キーの union（全部の名前空間）。t() の型は、useWimTranslation に渡した
// 名前空間から決まる（useWimTranslation.ts の WimKeyOf）。ここは、名前空間をまたいでキーを
// 受け渡す場所のための型。
${namespaces.map((ns) => `import type { ${nsTypeName(ns)} } from "./${ns}";`).join("\n")}

export type WimI18nKey =
${namespaces.map((ns) => `  | ${nsTypeName(ns)}\n  | \`${ns}:\${${nsTypeName(ns)}}\``).join("\n")};
`;
if (writeIfChanged(keysFile, keysContent)) changed++;

if (changed === 0) console.log("[i18n-resources] No changes.");
else console.log(`[i18n-resources] ${usedKeys.size} keys, ns: ${namespaces.join(", ")}`);
