import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/**
 * public/locales/en/ 内の JSON ファイル名から i18n Namespace を自動生成する
 */
export function generateI18nNamespaces() {
  const rootDir = path.resolve(__dirname, '..');
  const localesDir = path.resolve(rootDir, 'public/locales/en');
  const targetFile = path.resolve(rootDir, 'stories/i18nConstants.ts');

  if (!fs.existsSync(localesDir)) {
    console.warn(`Locales directory not found: ${localesDir}`);
    return;
  }

  try {
    const files = fs.readdirSync(localesDir);
    const namespaces = files
      .filter(file => file.endsWith('.json'))
      .map(file => file.replace('.json', ''))
      .sort();

    const content = `/**
 * This file is auto-generated by scripts/i18n-namespace-plugin.js
 * Do not edit this file manually.
 */
export const ALL_NAMESPACES = ${JSON.stringify(namespaces, null, 2)};\n`;

    // 内容が変わっていない場合は書き込まない（Vite の無限リスタート防止）
    if (fs.existsSync(targetFile)) {
      const currentContent = fs.readFileSync(targetFile, 'utf-8');
      if (currentContent === content) return;
    }

    fs.writeFileSync(targetFile, content);
    console.log(`[i18n-auto-namespace] Generated namespaces in ${path.relative(rootDir, targetFile)}`);
  } catch (error) {
    console.error('[i18n-auto-namespace] Error generating namespaces:', error);
  }
}

/**
 * Vite プラグイン
 */
export default function i18nAutoNamespacePlugin() {
  return {
    name: 'i18n-auto-namespace',
    buildStart() {
      generateI18nNamespaces();
    },
    handleHotUpdate({ file }) {
      // locale ファイルが更新された場合に再生成
      if (file.includes('public/locales/en')) {
        generateI18nNamespaces();
      }
    }
  };
}
