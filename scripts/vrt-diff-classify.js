/**
 * VRT のベースライン差分を「実変更」と「にじみ」に分ける判定（T69 → T81）。
 *
 * `vrt-color-shift-report.js` から切り出してある。画像を読む部分と分けておくと、
 * **実データで測った数値を固定資産にして判定だけを回帰テストできる**
 * （`vrt-diff-classify.test.js` と `fixtures/vrt-diff-metrics.json`）。
 *
 * ## 軸
 *
 * `shift` … 差分画素の平均色移動量。**符号付きの平均**である点が重要。
 * `area`  … 差分画素が画像に占める割合。
 * `strongPct` … 差分画素のうち、**いずれかのチャンネルが 64 以上動いた**ものの割合。
 *
 * ## なぜ `strongPct` が要るのか（T81・2026-08-07 の実測）
 *
 * `shift` は符号付き平均なので、**要素が動いただけの変更では相殺されて 0 になる**
 * ── 動いた先で「背景→前景」に変わる画素と、動いた元で「前景→背景」に変わる
 * 画素がほぼ同数出るため。`area` も、動いたのが小さな要素なら 1% に届かない。
 * **2 軸のどちらから見ても noise に落ちる。**
 *
 * これは理屈ではなく実測で出た。当時の規則を実際のコミットバックに当てると:
 *
 *   #277（`DataGrid` の列幅）  実変更 2 枚 → **2 枚とも noise**
 *   #278（`Alert` のアイコン位置）実変更 28 枚 → **28 枚とも noise**
 *
 * T81 の起票時は「アイコン 1 個の差し替えが noise になる」と書いていたが、
 * **実際にはレイアウトが動く変更のほぼ全部**が同じ穴に落ちていた。
 *
 * **「差分が狭い範囲に固まっているか」では分けられない。** 起票時に提案されていた
 * のはこの軸だったが、反例が同じデータの中にあった ── `media-audio--default` は
 * 589px が 51x16 の帯に fill 72% で固まっていて集中度では実変更に見えるが、両方の
 * リビジョンから切り出すと**同じ「0:00 / 0:01」**で、文字が別のラスタライズで
 * 描き直されただけだった。**「狭くて密」はアイコンの差し替えと文字の再描画を
 * 区別しない。**
 *
 * 分けられたのは**差分の大きさ**だった。にじみは前景色と背景色の**間**の値を
 * 行き来するので 1 画素あたりの変化は小さい。要素が動く・アイコンが変わると、
 * 画素は前景と背景の**両端**を飛ぶので大きく変わる。実測（3 組・303 枚）:
 *
 *   ノイズ 255 枚 … `strongPct` は **全枚数で 0**
 *   実変更  48 枚 … 13.1〜74.7（例外 1 枚は下記）
 *
 * ## 既知の限界
 *
 * **暗い背景で低コントラストに動いたものは拾えない。** dark の
 * `portal--custom-container` は実変更だが `strongPct = 0`（前景と背景の差が
 * 64 に届かない）。light 版は拾えるので、**ストーリー単位では表に出る**。
 *
 * **高コントラストな文字の再ラスタライズは誤検出しうる。** 上記の `audio` は
 * 灰色どうしだったので 0 だったが、黒地に白の文字が別位置で描き直されれば
 * `strongPct` は上がる。3 組のデータには 1 件も無かったが、原理的には残る。
 */

/** shift がこれ以上なら「塗り・文字色が動いた」。2026-07-30 の仕分けの実測値。 */
export const REPAINT_SHIFT = 41;

/** shift が小さくても、差分がこれだけ広ければ書体・描かれ方の変化を疑う。 */
export const GLYPH_AREA_PERCENT = 1;

/**
 * この割合の画素が「大きく」変わっていれば、にじみではなく何かが動いた。
 *
 * **ノイズ側は実測 255 枚すべてが 0** で、実変更の最小は 13.1。閾値はこの間に
 * 置けばよく、下限 0 に張り付かせない程度の余裕として 5 を採る。
 */
export const MOVED_STRONG_PERCENT = 5;

/** 1 画素が「大きく」変わったとみなすチャンネル差。前景と背景の両端を飛んだ印。 */
export const STRONG_CHANNEL_DELTA = 64;

/**
 * 分類。`reflow` / `added` / `removed` は画像を読む側が先に判定して渡す。
 *
 *   repaint … 塗り・文字色が動いた（平均色が大きく移動）
 *   moved   … 要素が動いた・差し替わった（大きく変わった画素が一定割合）
 *   glyph   … 色は動かないが差分が広い＝書体や描かれ方の変化
 *   noise   … 残り。フォントのにじみ・アンチエイリアスの揺れ
 */
export function classify({ shift, area, strongPct }) {
  if (shift >= REPAINT_SHIFT) return "repaint";
  if (strongPct >= MOVED_STRONG_PERCENT) return "moved";
  if (area >= GLYPH_AREA_PERCENT) return "glyph";
  return "noise";
}

/** 実変更として人が見るべきもの。`noise` 以外すべて。 */
export const REAL_KINDS = ["reflow", "added", "removed", "repaint", "moved", "glyph"];

/** 表示順。実変更を上に、その中では大きく変わったものを上に。 */
export const KIND_RANK = {
  reflow: 0,
  added: 0,
  removed: 0,
  repaint: 1,
  moved: 1,
  glyph: 2,
  noise: 3,
};
